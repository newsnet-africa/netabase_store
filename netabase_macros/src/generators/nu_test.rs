//! Nushell test script generation for CLI testing.
//!
//! This module generates comprehensive Nushell test scripts that exercise
//! all CLI endpoints with verbose output and granular test selection.

use proc_macro2::TokenStream;
use quote::quote;
use syn::Ident;

/// Generate a Nushell test script for a CLI.
///
/// Creates a comprehensive test suite that:
/// - Tests all CRUD operations (Create, Read, Update, Delete, List, Count)
/// - Tests both JSON and RON formats
/// - Tests schema commands
/// - Provides verbose output with test status
/// - Allows selective test execution
///
/// # Arguments
///
/// * `cli_name` - Name of the CLI binary
/// * `definitions` - List of (definition_name, model_names) tuples
///
/// # Returns
///
/// String containing the complete Nushell test script
pub fn generate_nu_test_script(
    cli_name: &str,
    definitions: &[(Ident, Vec<Ident>)],
) -> String {
    let mut script = String::new();
    
    // Header
    script.push_str(&format!(r#"#!/usr/bin/env nu
# Comprehensive test script for {} CLI
# Generated by netabase_store
#
# Usage:
#   nu test_cli.nu                    # Run all tests
#   nu test_cli.nu --tests schema     # Run only schema tests
#   nu test_cli.nu --tests user       # Run only user tests
#   nu test_cli.nu --tests create     # Run only create tests
#   nu test_cli.nu --help             # Show help

"#, cli_name));

    // Configuration
    script.push_str(r#"
# Test configuration
const TEST_DB = "./.test_db"
const CLI_BIN = "./target/debug/"

# Color codes for output
const COLOR_GREEN = "\u{001b}[32m"
const COLOR_RED = "\u{001b}[31m"
const COLOR_YELLOW = "\u{001b}[33m"
const COLOR_BLUE = "\u{001b}[34m"
const COLOR_RESET = "\u{001b}[0m"

# Test statistics
let test_stats = {
    total: 0,
    passed: 0,
    failed: 0,
    skipped: 0
}

# Print a section header
def print_section [title: string] {
    print $"($COLOR_BLUE)━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━($COLOR_RESET)"
    print $"($COLOR_BLUE)  ($title)($COLOR_RESET)"
    print $"($COLOR_BLUE)━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━($COLOR_RESET)"
}

# Print test result
def print_test [name: string, status: string, details: string = ""] {
    let symbol = if $status == "PASS" { "✓" } else if $status == "FAIL" { "✗" } else { "○" }
    let color = if $status == "PASS" { $COLOR_GREEN } else if $status == "FAIL" { $COLOR_RED } else { $COLOR_YELLOW }
    
    print $"  ($color)($symbol) ($name)($COLOR_RESET)"
    if ($details | str length) > 0 {
        print $"    ($details)"
    }
}

# Run a CLI command and capture output
def run_cli [...args: string] {
    let cmd = ([$CLI_BIN] ++ $args | str join " ")
    print $"    → Running: ($cmd)"
    
    try {
        let result = (do { ^$CLI_BIN ...$args } | complete)
        {
            success: ($result.exit_code == 0),
            stdout: $result.stdout,
            stderr: $result.stderr,
            exit_code: $result.exit_code
        }
    } catch {
        {
            success: false,
            stdout: "",
            stderr: $"Failed to execute command",
            exit_code: -1
        }
    }
}

# Setup test environment
def setup_test_env [] {
    print_section "Setting up test environment"
    
    # Clean up old test database
    if ($TEST_DB | path exists) {
        print $"  Removing old test database at ($TEST_DB)"
        rm -rf $TEST_DB
    }
    
    # Create fresh test database directory
    mkdir $TEST_DB
    print $"  ($COLOR_GREEN)✓ Test environment ready($COLOR_RESET)"
}

# Cleanup test environment
def cleanup_test_env [] {
    print_section "Cleaning up test environment"
    
    if ($TEST_DB | path exists) {
        rm -rf $TEST_DB
        print $"  ($COLOR_GREEN)✓ Test database removed($COLOR_RESET)"
    }
}

"#);

    // Generate schema tests
    script.push_str(r#"
# Test schema commands
def test_schema [] {
    print_section "Testing Schema Commands"
    
    # Test schema show
    print_test "schema show" "RUNNING"
    let result = (run_cli "--db-path" $TEST_DB "schema" "show")
    if $result.success {
        print_test "schema show" "PASS" $"Output: ($result.stdout | str substring 0..100)..."
    } else {
        print_test "schema show" "FAIL" $"Error: ($result.stderr)"
    }
    
    # Test schema tables
    print_test "schema tables" "RUNNING"
    let result = (run_cli "--db-path" $TEST_DB "schema" "tables")
    if $result.success {
        print_test "schema tables" "PASS" $"Output: ($result.stdout | str substring 0..100)..."
    } else {
        print_test "schema tables" "FAIL" $"Error: ($result.stderr)"
    }
    
    # Test schema stats
    print_test "schema stats" "RUNNING"
    let result = (run_cli "--db-path" $TEST_DB "schema" "stats")
    if $result.success {
        print_test "schema stats" "PASS" $"Output: ($result.stdout | str substring 0..100)..."
    } else {
        print_test "schema stats" "FAIL" $"Error: ($result.stderr)"
    }
}

"#);

    // Generate model-specific tests for each definition
    for (def_name, models) in definitions {
        let def_lower = def_name.to_string().to_lowercase();
        
        for model in models {
            let model_name = model.to_string();
            let model_lower = model_name.to_lowercase();
            
            // Build the test function piece by piece to avoid format string counting errors
            script.push_str(&format!("\n# Test {} CRUD operations\n", model_name));
            script.push_str(&format!("def test_{}_crud [] {{\n", model_lower));
            script.push_str(&format!("    print_section \"Testing {} CRUD Operations\"\n", model_name));
            script.push_str("    \n");
            
            // CREATE with JSON
            script.push_str(&format!("    # Test CREATE with JSON\n"));
            script.push_str(&format!("    print_test \"{} create (JSON)\" \"RUNNING\"\n", model_name));
            script.push_str("    let json_data = '{\"id\":\"test_id_1\",\"name\":\"Test Name\"}'\n");
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"create\" \"--json\" $json_data)\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} create (JSON)\" \"PASS\" $\"Created record: ($result.stdout | str substring 0..100)...\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} create (JSON)\" \"FAIL\" $\"Error: ($result.stderr)\"\n", model_name));
            script.push_str("        return\n");
            script.push_str("    }\n");
            script.push_str("    \n");
            
            // CREATE with RON
            script.push_str("    # Test CREATE with RON\n");
            script.push_str(&format!("    print_test \"{} create (RON)\" \"RUNNING\"\n", model_name));
            script.push_str("    let ron_data = '(id:\"test_id_2\",name:\"Test Name 2\")'\n");
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"create\" \"--ron\" $ron_data)\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} create (RON)\" \"PASS\" $\"Created record: ($result.stdout | str substring 0..100)...\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} create (RON)\" \"FAIL\" $\"Error: ($result.stderr)\"\n", model_name));
            script.push_str("    }\n");
            script.push_str("    \n");
            
            // LIST
            script.push_str("    # Test LIST\n");
            script.push_str(&format!("    print_test \"{} list\" \"RUNNING\"\n", model_name));
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"list\")\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} list\" \"PASS\" $\"Found records: ($result.stdout | str substring 0..200)...\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} list\" \"FAIL\" $\"Error: ($result.stderr)\"\n", model_name));
            script.push_str("    }\n");
            script.push_str("    \n");
            
            // LIST with limit
            script.push_str("    # Test LIST with limit\n");
            script.push_str(&format!("    print_test \"{} list --limit\" \"RUNNING\"\n", model_name));
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"list\" \"--limit\" \"1\")\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} list --limit\" \"PASS\" $\"Limited results: ($result.stdout | str substring 0..100)...\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} list --limit\" \"FAIL\" $\"Error: ($result.stderr)\"\n", model_name));
            script.push_str("    }\n");
            script.push_str("    \n");
            
            // LIST with RON format
            script.push_str("    # Test LIST with RON format\n");
            script.push_str(&format!("    print_test \"{} list (RON output)\" \"RUNNING\"\n", model_name));
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"list\" \"--format\" \"ron\")\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} list (RON output)\" \"PASS\" $\"RON output: ($result.stdout | str substring 0..100)...\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} list (RON output)\" \"FAIL\" $\"Error: ($result.stderr)\"\n", model_name));
            script.push_str("    }\n");
            script.push_str("    \n");
            
            // COUNT
            script.push_str("    # Test COUNT\n");
            script.push_str(&format!("    print_test \"{} count\" \"RUNNING\"\n", model_name));
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"count\")\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} count\" \"PASS\" $\"Count: ($result.stdout)\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} count\" \"FAIL\" $\"Error: ($result.stderr)\"\n", model_name));
            script.push_str("    }\n");
            script.push_str("    \n");
            
            // UPDATE with JSON
            script.push_str("    # Test UPDATE with JSON\n");
            script.push_str(&format!("    print_test \"{} update (JSON)\" \"RUNNING\"\n", model_name));
            script.push_str("    let update_json = '{\"id\":\"test_id_1\",\"name\":\"Updated Name\"}'\n");
            script.push_str(&format!("    let result = (run_cli \"--db-path\" $TEST_DB \"{}\" \"{}\" \"update\" \"--id\" \"test_id_1\" \"--json\" $update_json)\n", def_lower, model_lower));
            script.push_str("    if $result.success {\n");
            script.push_str(&format!("        print_test \"{} update (JSON)\" \"PASS\" $\"Updated: ($result.stdout | str substring 0..100)...\"\n", model_name));
            script.push_str("    } else {\n");
            script.push_str(&format!("        print_test \"{} update (JSON)\" \"SKIP\" $\"Not fully implemented: ($result.stderr | str substring 0..100)...\"\n", model_name));
            script.push_str("    }\n");
            script.push_str("}\n");
            script.push_str("\n");
        }
    }

    // Main test runner
    script.push_str(r#"
# Main test runner
def main [
    --tests: string = "all"  # Specific test to run (all, schema, user, post, create, etc.)
] {
    print $"($COLOR_BLUE)╔══════════════════════════════════════════════════════════════╗($COLOR_RESET)"
    print $"($COLOR_BLUE)║  CLI Comprehensive Test Suite                               ║($COLOR_RESET)"
    print $"($COLOR_BLUE)╚══════════════════════════════════════════════════════════════╝($COLOR_RESET)"
    print ""
    
    setup_test_env
    print ""
    
    # Run selected tests
    if $tests == "all" or $tests == "schema" {
        test_schema
        print ""
    }
    
"#);

    // Add test runners for each model
    for (def_name, models) in definitions {
        for model in models {
            let model_lower = model.to_string().to_lowercase();
            script.push_str(&format!(r#"    if $tests == "all" or $tests == "{}" {{
        test_{}_crud
        print ""
    }}
    
"#, model_lower, model_lower));
        }
    }

    script.push_str(r#"    cleanup_test_env
    print ""
    
    print_section "Test Summary"
    print $"  Total tests run: Check output above for results"
    print $"  ($COLOR_GREEN)All tests completed!($COLOR_RESET)"
}
"#);

    script
}

/// Generate the code that writes the Nushell test script to a file.
///
/// This generates Rust code that, when executed, will create the test script file.
pub fn generate_nu_test_script_writer(
    cli_name: &str,
    output_path: &str,
    definitions: &[(Ident, Vec<Ident>)],
) -> TokenStream {
    let script_content = generate_nu_test_script(cli_name, definitions);
    
    quote! {
        const _: () = {
            const SCRIPT_CONTENT: &str = #script_content;
            const OUTPUT_PATH: &str = #output_path;
            
            // This will be executed at build time via build script
            // or we can create a test that generates it
        };
        
        #[test]
        fn generate_test_script() {
            use std::io::Write;
            let script_content = #script_content;
            let mut file = std::fs::File::create(#output_path)
                .expect("Failed to create test script file");
            file.write_all(script_content.as_bytes())
                .expect("Failed to write test script");
            
            // Make the script executable on Unix systems
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let metadata = file.metadata()
                    .expect("Failed to get file metadata");
                let mut perms = metadata.permissions();
                perms.set_mode(0o755);
                std::fs::set_permissions(#output_path, perms)
                    .expect("Failed to set executable permissions");
            }
            
            println!("Generated test script at: {}", #output_path);
        }
    }
}
