/// Trait that aggregates all key types for a model.
///
/// This trait is automatically implemented by the `#[derive(NetabaseModel)]` macro.
/// It defines the six key types that a model can have, each serving a different
/// purpose in the storage and query system.
///
/// # Type Parameters
///
/// - `D`: The definition this model belongs to
/// - `M`: The model type itself
///
/// # Associated Types
///
/// Each associated type must implement both `redb::Key` (for storage) and its
/// corresponding trait (for model semantics):
///
/// - `Primary`: The primary key type (required, non-empty)
/// - `Secondary`: Secondary index keys (enum of possible indexes)
/// - `Relational`: Foreign key references (enum of link fields)
/// - `Subscription`: Pub/sub topic keys (enum of subscriptions)
/// - `Blob`: Large data chunk keys (enum of blob fields)
/// - `Libp2p`: P2P provider keys (for network discovery)
///
/// # Example
///
/// ```rust,ignore
/// // Generated by the NetabaseModel macro:
/// impl NetabaseModelKeys<MyDef, User> for UserKeys {
///     type Primary = UserId;
///     type Secondary = UserSecondaryKey;  // enum { Email, Phone, ... }
///     type Relational = UserRelationalKey; // enum { Company, Manager, ... }
///     type Subscription = UserSubscriptionKey;
///     type Blob = UserBlobKey;
///     type Libp2p = UserLibp2pKey;
/// }
/// ```
pub trait NetabaseModelKeys<D: NetabaseDefinition, M: NetabaseModelMarker<D>>:
    std::marker::Sized
where
    D::Discriminant: 'static + std::fmt::Debug,
    Self::Primary: redb::Key + 'static,
    Self::Secondary: redb::Key + 'static,
    Self::Relational: redb::Key + 'static,
    Self::Subscription: redb::Key + 'static,
{
    /// Primary key type - uniquely identifies model instances.
    type Primary: NetabaseModelPrimaryKey<D, M>;
    /// Secondary key type - enum of all secondary indexed fields.
    type Secondary: NetabaseModelSecondaryKey<D, M>;
    /// Relational key type - enum of all foreign key fields.
    type Relational: NetabaseModelRelationalKey<D, M>;
    /// Subscription key type - enum of all pub/sub topics.
    type Subscription: NetabaseModelSubscriptionKey<D, M> + 'static;
    /// Blob key type - enum of all large data fields.
    type Blob: NetabaseModelBlobKey<D, M>;
    /// Libp2p key type - for P2P provider advertisement.
    type Libp2p: NetabaseModelLibp2pProviderKey<D, M>;
}

/// Trait for extracting the inner value from a key wrapper type.
///
/// Many key types wrap an inner value (e.g., `UserId(String)`). This trait
/// provides a uniform interface for accessing the wrapped value.
pub trait NetabaseKeyWrapper {
    /// The inner type being wrapped.
    type Inner: ?Sized;
    
    /// Get a reference to the inner value.
    fn as_inner(&self) -> &Self::Inner;
    
    /// Consume self and return the inner value.
    fn into_inner(self) -> Self::Inner;
}
