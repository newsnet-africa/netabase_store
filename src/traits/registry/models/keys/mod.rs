//! Key trait definitions for models.
//!
//! This module provides the trait system for all key types used by models.
//! Keys are fundamental to how models are stored, indexed, and queried in Netabase.
//!
//! # Key Types
//!
//! Each model has multiple key types for different purposes:
//!
//! ## Primary Keys ([`primary`])
//! - Unique identifier for each model instance
//! - Required for all models
//! - Used for direct lookups and updates
//!
//! ## Secondary Keys ([`secondary`])
//! - Additional indexed fields for fast queries
//! - Optional, can have multiple per model
//! - Example: Email address on a User model
//!
//! ## Relational Keys ([`relational`])
//! - Type-safe foreign key references to other models
//! - Optional, enforces repository boundaries
//! - Example: `author_id` linking Post to User
//!
//! ## Blob Keys ([`blob`])
//! - Keys for large binary data chunks
//! - Auto-generated for fields marked with `#[blob]`
//! - Handles data > 60KB via chunking
//!
//! ## Subscription Keys ([`subscription`])
//! - Topic-based pub/sub membership
//! - Optional, for P2P synchronization
//! - Example: User subscribing to a hashtag
//!
//! ## Libp2p Keys ([`libp2p`])
//! - P2P provider advertisement keys
//! - Used in distributed network discovery
//!
//! # The NetabaseModelKeys Trait
//!
//! The [`NetabaseModelKeys`] trait aggregates all key types for a model. It's
//! automatically implemented by the `#[derive(NetabaseModel)]` macro.
//!
//! # Example
//!
//! ```rust,ignore
//! // The macro generates a Keys type that implements NetabaseModelKeys:
//! #[derive(NetabaseModel)]
//! pub struct User {
//!     #[primary_key]
//!     pub id: UserId,           // -> Keys::Primary
//!     
//!     #[secondary_key]
//!     pub email: String,        // -> Keys::Secondary (Email variant)
//!     
//!     #[link(MyDef, Company)]
//!     pub company: CompanyId,   // -> Keys::Relational (Company variant)
//! }
//! ```

